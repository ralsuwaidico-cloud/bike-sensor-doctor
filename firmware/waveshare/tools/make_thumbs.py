#!/usr/bin/env python3
"""Ride-screen preview pictures for Settings > Display > Ride screen.
Reads the PC harness renders (test/sim/out/21_ride_<X>_live.ppm, drawn by the firmware's own code) and writes
main/ui/ui_thumbs.c: one 100 x 100 RGB565+alpha (RGB565A8) image per design, round-masked.
Run after `make run` in test/sim whenever a design changes:  python3 tools/make_thumbs.py"""
import os, sys
from PIL import Image, ImageDraw
here = os.path.dirname(os.path.abspath(__file__)); fw = os.path.dirname(here)
src = os.path.join(fw, 'test', 'sim', 'out'); S = 100
letters = sys.argv[1:] or ['A', 'B', 'C']
out = ['/* GENERATED by tools/make_thumbs.py from the PC harness renders - do not edit by hand. */', '#include "ui.h"', '']
names = []
for L in letters:
    im = Image.open(os.path.join(src, f'21_ride_{L}_live.ppm')).convert('RGB').resize((S, S), Image.LANCZOS)
    m = Image.new('L', (S * 4, S * 4), 0); ImageDraw.Draw(m).ellipse((0, 0, S * 4 - 1, S * 4 - 1), fill=255); m = m.resize((S, S), Image.LANCZOS)
    rgb = bytearray(); a = bytearray()
    for y in range(S):
        for x in range(S):
            r, g, b = im.getpixel((x, y)); v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            rgb += bytes((v & 0xFF, v >> 8)); a.append(m.getpixel((x, y)))
    data = rgb + a; n = f'thumb_{L.lower()}'; names.append(n)
    out.append(f'static const uint8_t {n}_map[] = {{')
    for i in range(0, len(data), 24): out.append('    ' + ','.join(f'0x{c:02x}' for c in data[i:i + 24]) + ',')
    out.append('};')
    out.append(f'static const lv_image_dsc_t {n} = {{ .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8, .w = {S}, .h = {S}, .stride = {S * 2} }},')
    out.append(f'    .data_size = sizeof {n}_map, .data = {n}_map }};')
    out.append('')
out.append('static const lv_image_dsc_t *const THUMBS[] = { ' + ', '.join('&' + n for n in names) + ' };')
out.append('const lv_image_dsc_t *ui_ride_thumb(int i) { return i >= 0 && i < (int)(sizeof THUMBS / sizeof THUMBS[0]) ? THUMBS[i] : NULL; }')
open(os.path.join(fw, 'main', 'ui', 'ui_thumbs.c'), 'w').write('\n'.join(out) + '\n')
print('wrote', len(names), 'thumbnails')
