#!/usr/bin/env python3
"""Rasterises the approved v3 line icons (prototype icon set, 24-unit viewBox) into LVGL 8-bit alpha images.
Output: src/ui/v3/cyv3_icons.c. The colour is applied at run time (img_recolor), so one bitmap serves every theme.
Needs: pip install playwright && playwright install chromium (generation only; the firmware build uses the committed .c)."""
import pathlib, sys
from playwright.sync_api import sync_playwright

P = {   # path data copied from the approved prototype (Deliverable D, src/core.js)
    'face':  '<circle cx="12" cy="12" r="8"/><path d="M12 7v5l3 2"/>',
    'today': '<rect x="4" y="5" width="16" height="15" rx="2"/><path d="M4 10h16M9 3v4M15 3v4"/>',
    'plan':  '<path d="M5 18l4-6 3 3 6-9"/>',
    'heart': '<path d="M12 20s-7-4.4-7-10a4 4 0 017-2.6A4 4 0 0119 10c0 5.6-7 10-7 10z"/>',
    'coach': '<path d="M5 6h14v9H9l-4 3z"/><path d="M9 10h6"/>',
    'hist':  '<circle cx="12" cy="12" r="8"/><path d="M12 8v4l3 2"/>',
    'util':  '<rect x="4" y="4" width="6" height="6" rx="1.5"/><rect x="14" y="4" width="6" height="6" rx="1.5"/><rect x="4" y="14" width="6" height="6" rx="1.5"/><rect x="14" y="14" width="6" height="6" rx="1.5"/>',
    'gear':  '<circle cx="12" cy="12" r="3"/><path d="M12 3v3M12 18v3M3 12h3M18 12h3M5.6 5.6l2.1 2.1M16.3 16.3l2.1 2.1M5.6 18.4l2.1-2.1M16.3 7.7l2.1-2.1"/>',
    'bike':  '<circle cx="6" cy="16" r="3.5"/><circle cx="18" cy="16" r="3.5"/><path d="M6 16l4-7h5l3 7M10 9l-1.5-3H6.5M14 6h2.5"/>',
    'chev':  '<path d="M9 5l7 7-7 7"/>',
    'chevl': '<path d="M15 5l-7 7 7 7"/>',
    'down':  '<path d="M6 9l6 6 6-6"/>',
    'bolt':  '<path d="M13 3L5 14h6l-1 7 8-11h-6z"/>',
    'check': '<path d="M5 12.5l4.5 4.5L19 7.5"/>',
    'warn':  '<path d="M12 4l9 16H3z"/><path d="M12 10v4M12 17v.5"/>',
}
# name, icon, pixel size, stroke width (as used by the prototype at that size)
OUT = [('row', n, 20, 1.8) for n in ['face', 'today', 'plan', 'heart', 'coach', 'hist', 'util', 'gear', 'bike']] + \
      [('chev', 'chev', 12, 2.4), ('chevl', 'chevl', 12, 2.4), ('more', 'down', 11, 2.6), ('bolt', 'bolt', 12, 2.0), ('check', 'check', 15, 2.6), ('warn', 'warn', 15, 2.2)]

def main():
    root = pathlib.Path(__file__).resolve().parents[2]
    dst = root / 'src/ui/v3/cyv3_icons.c'
    lines = ['// Generated by tools/v3/gen_icons.py — do not edit. 8-bit alpha icons, recoloured at run time.', '#if defined(CYW_V3POC)', '#include <lvgl.h>', '']
    names = []
    with sync_playwright() as p:
        b = p.chromium.launch(); pg = b.new_page(device_scale_factor=1)
        for kind, n, px, sw in OUT:
            svg = f'<svg xmlns="http://www.w3.org/2000/svg" width="{px}" height="{px}" viewBox="0 0 24 24" fill="none" stroke="#fff" stroke-width="{sw}" stroke-linecap="round" stroke-linejoin="round">{P[n]}</svg>'
            pg.set_content(f'<html><body style="margin:0;background:transparent">{svg}</body></html>')
            js = f'''async () => {{ const c = document.createElement('canvas'); c.width = {px}; c.height = {px}; const g = c.getContext('2d');
              const img = new Image(); img.src = 'data:image/svg+xml,' + encodeURIComponent(document.body.innerHTML); await img.decode(); g.drawImage(img, 0, 0);
              return Array.from(g.getImageData(0, 0, {px}, {px}).data).filter((_, i) => i % 4 === 3); }}'''
            alpha = pg.evaluate(js)
            sym = f'cyv3_ic_{n}_{px}'; names.append(sym)
            lines.append(f'static const uint8_t {sym}_map[] = {{' + ','.join(str(a) for a in alpha) + '};')
            lines.append(f'const lv_img_dsc_t {sym} = {{ {{LV_IMG_CF_ALPHA_8BIT, 0, 0, {px}, {px}}}, {px * px}, {sym}_map }};')
            lines.append('')
        b.close()
    lines.append('#endif /* CYW_V3POC */'); dst.write_text('\n'.join(lines) + '\n')
    print('wrote', dst, len(names), 'icons:', ' '.join(names))

if __name__ == '__main__':
    sys.exit(main())
