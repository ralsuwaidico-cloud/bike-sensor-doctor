#!/usr/bin/env python3
"""Generates src/ui/v3/cyv3_tokens.hpp from the approved design-system tokens (Deliverable A, tokens.json).
`--check` exits non-zero when the committed header differs from what tokens.json produces (used by the host tests)."""
import json, pathlib, sys
here = pathlib.Path(__file__).resolve().parent
root = here.parents[1]
tok = json.loads((here / 'tokens.json').read_text())
themes = [t['id'] for t in tok['color']['themes']]
colors = [t for t in tok['color']['tokens'] if isinstance(t['value'], dict)]
ident = lambda s: s.replace('-', '_')
o = ['#pragma once', '// Generated by tools/v3/gen_tokens.py from tools/v3/tokens.json (design system v%s). Do not edit.' % tok['version'],
     '#include <cstdint>', 'namespace cyw::v3 {', '',
     'enum class ThemeId : uint8_t { ' + ', '.join(ident(t).capitalize() for t in themes) + ' };',
     'struct Palette {']
o += ['    uint32_t %s;' % ident(c['name']) for c in colors]
o += ['};', '', 'inline const Palette& palette(ThemeId t) {', '    static const Palette P[] = {']
for th in themes:
    vals = ', '.join('0x%s' % c['value'][th].lstrip('#').lower() for c in colors)
    o.append('        {%s},   // %s' % (vals, th))
o += ['    };', '    return P[static_cast<int>(t)];', '}', '']
for grp in ('spacing', 'radius', 'size'):
    for t in tok[grp]['tokens']:
        v = t['value']
        if v.endswith('px'): o.append('constexpr int %s = %s;   // %s' % (ident(t['name']).upper(), v[:-2], t.get('usage', '').split('. ')[0].rstrip('.')))
o += ['', '} // namespace cyw::v3', '']
text = '\n'.join(o)
dst = root / 'src/ui/v3/cyv3_tokens.hpp'
if '--check' in sys.argv:
    ok = dst.exists() and dst.read_text() == text
    print('tokens header', 'matches tokens.json' if ok else 'DIFFERS from tokens.json'); sys.exit(0 if ok else 1)
dst.write_text(text); print('wrote', dst)
